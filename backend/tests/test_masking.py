import pytest

from zheka.core.masking import mask_pii


@pytest.mark.parametrize(
    ("text", "masked"),
    [
        ("звоните +7 (917) 123-45-67", "звоните [ТЕЛЕФОН]"),
        ("звоните 89171234567", "звоните [ТЕЛЕФОН]"),
        ("мой номер 8-917-123-45-67.", "мой номер [ТЕЛЕФОН]."),
        ("домашний 123-45-67", "домашний [ТЕЛЕФОН]"),
        ("пишите на ivan.petrov@mail.ru", "пишите на [EMAIL]"),
        ("лс 1234567890", "лс [НОМЕР]"),
        ("СНИЛС 12345678901", "СНИЛС [НОМЕР]"),
        ("течет в кв. 45", "течет в [КВАРТИРА]"),
        ("Кв.45а без воды", "[КВАРТИРА] без воды"),
        ("квартира 12", "[КВАРТИРА]"),
        ("в квартире № 7 темно", "в [КВАРТИРА] темно"),
        ("шумят в 7-й квартире", "шумят в [КВАРТИРА]"),
        ("соседи из 45 квартиры топят", "соседи из [КВАРТИРА] топят"),
        ("12-я квартира без света", "[КВАРТИРА] без света"),
        ("в квартире номер 12 темно", "в [КВАРТИРА] темно"),
        ("дом 5 квартира 12", "дом 5 [КВАРТИРА]"),
        (
            "Течет стояк в кв. 45, звоните 8 917 123-45-67",
            "Течет стояк в [КВАРТИРА], звоните [ТЕЛЕФОН]",
        ),
    ],
)
def test_personal_data_is_replaced(text: str, masked: str) -> None:
    assert mask_pii(text) == masked


@pytest.mark.parametrize(
    "text",
    [
        "батареи 45 градусов",
        "2 подъезд",
        "свет не горит с 8 до 20",
        "дом 61/1, 3 этаж",
        "с 01.09.2026 нет горячей воды",
        "Иван Петров, ул. Ленина, д. 5",
    ],
)
def test_other_text_stays(text: str) -> None:
    assert mask_pii(text) == text
